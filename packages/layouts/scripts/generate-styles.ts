// Write `src/styles.css`, the stylesheet of the `Layout` component, from the
// sheets in `src/css`. Each sheet holds the rules of one feature or part, inside
// `@layer pierre-layouts`, so that a module can render only the sheets that an
// app uses. An app that renders `Layout` imports `styles.css`, which holds
// every sheet. Run `moon run layouts:generate-styles` after a change to a
// sheet; a unit test checks that `styles.css` is current.
import { readFileSync, writeFileSync } from 'node:fs';

/** The sheets of `styles.css`, in their order in the file. */
export const STYLE_SHEETS: readonly string[] = [
  'split',
  'content',
  'flip',
  'focus-ring',
  'zoom',
  'drop',
  'headers',
  'tabs',
  'tab-drag',
  'corners',
];

const SOURCE = new URL('../src/', import.meta.url);

const NOTICE = `/* Generated by scripts/generate-styles.ts from the sheets in src/css. Change
   a sheet, then run "moon run layouts:generate-styles". */
`;

/** The text of `styles.css`: a notice, then each sheet in order. */
export function generateStylesheet(): string {
  return [
    NOTICE,
    ...STYLE_SHEETS.map((name) =>
      readFileSync(new URL(`css/${name}.css`, SOURCE), 'utf8')
    ),
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(new URL('styles.css', SOURCE), generateStylesheet());
}
