import binaryen from 'binaryen';
// Emit everything the Rust crate, translator, and benchmarks read:
// - gen/highlights.named.wasm: preprocessed WAT compiled without Binaryen, with
//   function, local, and global names kept so the generated Rust is readable.
// - gen/highlights.native.wasm: Binaryen-optimized with names kept, which the
//   translator reads.
// - gen/highlights.opt.wasm: the published, Binaryen-optimized module, which the
//   JS side of the benchmark runs.
// - gen/token-types.json and gen/languages.json: the token and language tables,
//   plus highlights/src/generated/languages.rs for the crate.
// - gen/pierre-dark.table: the packed theme table JS writes to Wasm memory.
// - gen/bench/: one input per language (its test sample repeated to about
//   128 KiB) plus the real benchmark fixtures, listed in manifest.json.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import wabt from 'wabt';

import { prepareTheme } from '../../lib/theme';
import {
  listTokenTypes,
  optimizeWasm,
  transformWat,
} from '../../scripts/build';
import { samples } from '../../test/_samples';
import pierreDark from '../../themes/pierre-dark.json' with { type: 'json' };

const { parseWat } = await wabt();
const sourceUrl = new URL('../../src/highlights.wat', import.meta.url);
const outUrl = new URL('../gen/', import.meta.url);
mkdirSync(outUrl, { recursive: true });

const { code, enumMap, languages } = transformWat(sourceUrl);
const named = compileNamed(code);
writeFileSync(new URL('highlights.named.wasm', outUrl), named);
const optimized = optimizeWasm(named);
// The Rust host calls these internal functions directly, so export them to
// keep standalone copies through Binaryen's inlining.
const hostEntryPoints = ['$lvCaptureBlob'];
const nativeCode =
  code.trimEnd().replace(/\)$/, '') +
  hostEntryPoints
    .map((name) => `  (export "${name.slice(1)}" (func ${name}))\n`)
    .join('') +
  ')\n';
writeFileSync(
  new URL('highlights.native.wasm', outUrl),
  optimizeNamed(compileNamed(nativeCode))
);
writeFileSync(new URL('highlights.opt.wasm', outUrl), optimized);
writeFileSync(
  new URL('token-types.json', outUrl),
  JSON.stringify(listTokenTypes(enumMap), null, 2) + '\n'
);
writeFileSync(
  new URL('languages.json', outUrl),
  JSON.stringify(languages, null, 2) + '\n'
);

const generatedUrl = new URL('../highlights/src/generated/', import.meta.url);
mkdirSync(generatedUrl, { recursive: true });
writeFileSync(
  new URL('languages.rs', generatedUrl),
  '// @generated by scripts/gen.ts - do not edit\n\n' +
    '/// Language ids by name and alias.\n' +
    'pub static LANGUAGES: &[(&str, u8)] = &[\n' +
    Object.entries(languages)
      .map(([name, id]) => `    ("${name}", ${id}),\n`)
      .join('') +
    '];\n'
);

writeFileSync(
  new URL('token_types.rs', generatedUrl),
  '// @generated by scripts/gen.ts - do not edit\n\n' +
    '/// `$Token` names in theme-table order.\n' +
    'pub static TOKEN_TYPES: &[&str] = &[\n' +
    listTokenTypes(enumMap)
      .map((name) => `    "${name}",\n`)
      .join('') +
    '];\n'
);

writeFileSync(
  new URL('token_ids.rs', generatedUrl),
  '// @generated by scripts/gen.ts - do not edit\n\n' +
    '//! `$Token` ids for the native lexers.\n\n' +
    listTokenTypes(enumMap)
      .map(
        (name, id) =>
          `pub const ${name.toUpperCase().replace(/[^A-Z0-9]/g, '_')}: u32 = ${id};\n`
      )
      .join('')
);

const table = prepareTheme(pierreDark).table;
if (table === undefined) throw new Error('pierre-dark has no packed table');
writeFileSync(new URL('pierre-dark.table', outUrl), table);

const fixturesUrl = new URL('../../benchmark/fixtures/', import.meta.url);

// Benchmark inputs for every language: the test sample repeated to about
// 128 KiB, plus the real fixtures. Labels name the language and the source.
const benchUrl = new URL('bench/', outUrl);
mkdirSync(benchUrl, { recursive: true });
const manifest: { file: string; lang: string; label: string }[] = [];
for (const [lang, { code }] of Object.entries(samples).sort(([a], [b]) =>
  a.localeCompare(b)
)) {
  if (!(lang in languages)) throw new Error(`sample ${lang} is not a language`);
  const file = `${lang}.sample.txt`;
  writeFileSync(
    new URL(file, benchUrl),
    code.repeat(Math.ceil(131072 / code.length))
  );
  manifest.push({ file, lang, label: lang });
}
for (const name of ['large.css', 'large.html', 'large.jsonc', 'large.ts']) {
  const lang = name.split('.')[1];
  const file = `${lang}.fixture.txt`;
  writeFileSync(
    new URL(file, benchUrl),
    readFileSync(new URL(`${name}.txt`, fixturesUrl))
  );
  manifest.push({ file, lang, label: `${lang} (${name}.txt)` });
}
writeFileSync(
  new URL('manifest.json', benchUrl),
  JSON.stringify(manifest, null, 2) + '\n'
);

/** Compile preprocessed WAT with function, local, and global names kept. */
function compileNamed(text: string): Uint8Array {
  const wasmModule = parseWat(sourceUrl.pathname, text, {
    bulk_memory: true,
    simd: true,
  });
  try {
    wasmModule.resolveNames();
    return wasmModule.toBinary({ write_debug_names: true }).buffer;
  } finally {
    wasmModule.destroy();
  }
}

/**
 * Binaryen -O3 like the published build, but keep the name section and skip
 * the JavaScriptCore workarounds, so the translated Rust and its profiles
 * show WAT function names.
 */
function optimizeNamed(bytes: Uint8Array): Uint8Array {
  binaryen.setOptimizeLevel(3);
  binaryen.setShrinkLevel(1);
  binaryen.setDebugInfo(true);
  try {
    for (let pass = 0; pass < 3; pass++) {
      const mod = binaryen.readBinary(bytes);
      try {
        mod.setFeatures(
          binaryen.Features.BulkMemory |
            binaryen.Features.BulkMemoryOpt |
            binaryen.Features.SIMD128
        );
        mod.optimize();
        bytes = mod.emitBinary();
      } finally {
        mod.dispose();
      }
    }
  } finally {
    binaryen.setDebugInfo(false);
  }
  return bytes;
}
