function IconGlyph({
  className = 'size-6',
  color,
  source,
}: {
  className?: string;
  color: string;
  source: string;
}) {
  const maskImage = `url("${source}")`;

  return (
    <span
      aria-hidden="true"
      className={`${className} shrink-0`}
      style={{
        backgroundColor: color,
        maskImage,
        maskPosition: 'center',
        maskRepeat: 'no-repeat',
        maskSize: 'contain',
        WebkitMaskImage: maskImage,
        WebkitMaskPosition: 'center',
        WebkitMaskRepeat: 'no-repeat',
        WebkitMaskSize: 'contain',
      }}
    />
  );
}

